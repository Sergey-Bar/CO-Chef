def get_or_create_ingredient(db: Session, name: str, **attrs) -> Ingredient:
    existing = db.query(Ingredient).filter(Ingredient.name == name).first()
    if existing:
        return existing
    ing = Ingredient(name=name, **attrs)
    db.add(ing)
    db.flush()
    return ing


def find_ingredient_by_alias(db: Session, term: str) -> Ingredient | None:
    term_l = term.strip().lower()
    q = db.query(Ingredient)
    for ing in q.all():
        if ing.name.lower() == term_l:
            return ing
        for alias in (ing.aliases or []):
            if alias.lower() == term_l:
                return ing
    return None


def seed_ingredients(db: Session):
    for (name, category, aliases, unit, cost, density) in INGREDIENT_SEEDS:
        get_or_create_ingredient(
            db, name, category=category, aliases=aliases,
            default_unit=unit, cost_per_unit=cost, density=density,
        )
    db.commit()


def seed_recipes(db: Session):
    for (name, desc, cat, cuisine, model, base, ppl, prep, allergens, lines) in RECIPE_SEEDS:
        recipe = db.query(Recipe).filter(Recipe.name == name).first()
        if recipe is None:
            recipe = Recipe(
                name=name, description=desc, category=cat, cuisine=cuisine, source="builtin",
                scaling_model=model, base_servings=base, people_per_batch=ppl,
                allergens=allergens, prep_time_min=prep,
            )
            db.add(recipe)
            db.flush()
            for (ing_name, qty, unit) in lines:
                ing = get_or_create_ingredient(db, ing_name)
                db.add(RecipeIngredient(recipe_id=recipe.id, ingredient_id=ing.id,
                                        quantity=qty, unit=unit))
        elif recipe.cuisine is None:
            recipe.cuisine = cuisine
            recipe.category = cat
    db.commit()


def seed_nutrition(db: Session):
    for name, (ref_unit, cal, prot, carbs, fat, sodium, sugar) in NUTRITION_DATA.items():
        ing = db.query(Ingredient).filter(Ingredient.name == name).first()
        if ing is None or ing.nutrition is not None:
            continue
        db.add(Nutrition(
            ingredient_id=ing.id, calories=cal, protein_g=prot,
            carbs_g=carbs, fat_g=fat, sodium_mg=sodium, sugar_g=sugar,
            reference_unit=ref_unit,
        ))
    db.commit()


def seed_price_book(db: Session):
    """Seed an initial effective price entry for every ingredient that has a cost."""
    today = date.today().isoformat()
    for ing in db.query(Ingredient).all():
        if ing.cost_per_unit is None:
            continue
        existing = db.query(PriceBook).filter(PriceBook.ingredient_id == ing.id).first()
        if existing is None:
            db.add(PriceBook(
                ingredient_id=ing.id, unit=ing.default_unit,
                price_per_unit=ing.cost_per_unit, effective_date=today,
            ))
    db.commit()


def seed_all(db: Session):
    seed_ingredients(db)
    seed_recipes(db)
    seed_nutrition(db)
    seed_price_book(db)
